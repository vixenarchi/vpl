import { chromium } from 'playwright';
const B = 'https://vi.terg.hr';
const br = await chromium.launch();
const pg = await br.newPage({ viewport: { width: 1280, height: 900 } });
await pg.goto(B, { waitUntil: 'networkidle' });
await pg.fill('#email', 'vpl-agent@terg.hr');
await pg.fill('#pass', 'agent-vpl-2026!');
await pg.click('#btn-login');
await pg.waitForSelector('#app:not([hidden])');
await pg.waitForTimeout(1500);
await pg.click('.step[data-stage="selection"]');
await pg.waitForTimeout(400);
await pg.screenshot({ path: '/tmp/p-select.png' });
const geo = await pg.evaluate(() => [...document.querySelectorAll('.band')].map((b) => {
  const r = b.getBoundingClientRect();
  const n = b.querySelector('.band-n').getBoundingClientRect();
  return [b.dataset.stage, Math.round(r.width), Math.round(n.right - r.left), Math.round(r.right - n.right)];
}));
console.log(JSON.stringify(geo));
await pg.click('.step[data-stage="ideation"]');
await pg.click('#btn-theme');
await pg.waitForTimeout(400);
await pg.screenshot({ path: '/tmp/p-dark.png' });
await br.close();
