-- v2.3 — sharing: a link for the whole internet, or a role for one person.
--
-- §4.1 says "no second table", and that still holds for notes: what gets
-- shared is a note and its subtree, and a per-row grant addressed to an email
-- cannot live in a column of `notes`. Encoding "who may read this" in an array
-- and then checking it inside RLS is possible and worse: the client would have
-- to write the array, RLS would have to trust it, and one malformed value
-- would open a subtree. One small table of grants, enforced by Postgres, is
-- lighter than a server that decides who may read what.
--
-- Two kinds of grant, one row each:
--   code  not null → a public link. read-only, works signed out.
--   email not null → that account, with role 'view' or 'edit'.
--
-- A grant covers the note it names and every note under it, so a whole
-- chapter of a knowledge tree is shared with one link.
-- Re-runnable.

-- ── 1. the grants ──────────────────────────────────────────────────────
create table if not exists public.note_shares (
  id          uuid primary key default gen_random_uuid(),
  note_id     uuid not null references public.notes(id) on delete cascade,
  owner_id    uuid not null default auth.uid() references auth.users(id) on delete cascade,

  -- exactly one of the two targets, never both, never neither
  code        text unique,
  email       text,
  role        text not null default 'view' check (role in ('view', 'edit')),

  created_at  timestamptz not null default now(),

  constraint note_shares_one_target check ((code is null) <> (email is null))
);

-- A public code is generated by the database, not by the client: the client
-- should not be able to choose a guessable or a repeated link. 64 bits of it.
alter table public.note_shares
  alter column code set default substring(replace(gen_random_uuid()::text, '-', '') from 1 for 16);

create index if not exists note_shares_note_idx on public.note_shares (note_id);
create index if not exists note_shares_email_idx
  on public.note_shares (lower(email)) where email is not null;

-- One row per note-and-person: re-sharing to the same email changes the role
-- instead of stacking grants that disagree with each other.
create unique index if not exists note_shares_note_email_key
  on public.note_shares (note_id, lower(email)) where email is not null;

comment on column public.note_shares.code is
  'Public link token. Read-only for anyone, signed in or not.';
comment on column public.note_shares.email is
  'Lowercased address of the one account this grant is for.';
comment on column public.note_shares.role is
  'view = read and render. edit = also change the content.';

-- ── 2. "may this viewer touch this note?" ──────────────────────────────
-- Walks up the parent chain from the note and returns the nearest grant's
-- role. Bounded depth so a cycle in parent_id cannot hang a query.
-- SECURITY DEFINER because it has to see grants and ancestors the caller
-- cannot read; it returns only a role, never a row.
create or replace function public.share_role(note uuid, viewer_email text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  with recursive up as (
    select n.id, n.parent_id, 0 as depth
      from public.notes n
     where n.id = note
    union all
    select p.id, p.parent_id, up.depth + 1
      from public.notes p
      join up on p.id = up.parent_id
     where up.depth < 64
  )
  select s.role
    from up
    join public.note_shares s on s.note_id = up.id
   where s.code is not null
      or (viewer_email is not null and lower(s.email) = lower(viewer_email))
   order by up.depth
   limit 1;
$$;

comment on function public.share_role(uuid, text) is
  'Nearest grant covering this note or one of its ancestors: view, edit, or null.';

-- ── 3. grants are visible to whom they are useful ──────────────────────
alter table public.note_shares enable row level security;

-- the owner manages the grants for notes it owns, and only those
drop policy if exists "shares by owner" on public.note_shares;
create policy "shares by owner" on public.note_shares
  for all to authenticated
  using (owner_id = auth.uid())
  with check (
    owner_id = auth.uid()
    and exists (
      select 1 from public.notes n
       where n.id = note_id and n.user_id = auth.uid()
    )
  );

-- the invited account can see the grant addressed to it, so the app can list
-- "shared with me" without guessing
drop policy if exists "shares for me" on public.note_shares;
create policy "shares for me" on public.note_shares
  for select to authenticated
  using (email is not null and lower(email) = lower(auth.jwt() ->> 'email'));

-- a public code has to be resolvable without an account: that is the point
drop policy if exists "shares by code" on public.note_shares;
create policy "shares by code" on public.note_shares
  for select to anon, authenticated
  using (code is not null);

-- ── 4. what a grant lets you do to the notes ───────────────────────────
drop policy if exists "shared read" on public.notes;
create policy "shared read" on public.notes
  for select to anon, authenticated
  using (public.share_role(id, lower(auth.jwt() ->> 'email')) is not null);

drop policy if exists "shared edit" on public.notes;
create policy "shared edit" on public.notes
  for update to authenticated
  using (public.share_role(id, lower(auth.jwt() ->> 'email')) = 'edit')
  with check (public.share_role(id, lower(auth.jwt() ->> 'email')) = 'edit');

-- ── 5. a share may move content, never ownership ───────────────────────
-- RLS runs after the row is written, so `with check` on the new row cannot
-- tell whether user_id changed. Column privileges can: an update may touch
-- the content columns and nothing else, so no edit share can hand a note to
-- another account (or publish it through the old `is_public` policy).
revoke update on public.notes from anon, authenticated;
grant update (title, body, tags, parent_id, position, deleted_at)
  on public.notes to authenticated;
